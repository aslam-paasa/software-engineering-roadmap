/**
 * Function with Three Inputs:
 * Q. Define a function calculateVolume that takes three parameters:
 *    length(number), width(number), height(number). The function
 *    should calculate and return the volume of a box using the formula
 *    length * width * height.
 * */ 

function calculateVolume(length: number, width: number, height: number): number {
    return length * width * height;
}