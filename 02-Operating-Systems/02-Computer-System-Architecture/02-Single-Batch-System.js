/**
 * Single Batch System:
 * 
 * 1. Situation in Early Computers:
 *    - In early days, there was no proper Operating System like today.
 *    - Computers were very large and expensive machines.
 *    - Programs were not loaded automatically.
 * 
 * 2. The Main Problem:
 *    - Programs were loaded manually using punch cards:
 *    - That means:
 *      a. A user would write a program.
 *      b. The operator (a person who handled the computer would load
 *         that program into the machine using punch card)
 *      c. The program would run.
 *      d. After it finishes, the operator had to remove it.
 *      e. Then the next program was loaded manually.
 *    - During this time:
 *      > The CPU stayed idle.
 *      > A lot of time was wasted.
 *      > Human effort was required again and again.
 *      > The computer was not used efficiently.
 *    - So the core problem was:
 *      "There was no automatic way to execute multiple programs 
 *       continuously, and everything depended on manual loading and
 *       human intervention". 
 * 
 * 3. The Solution: Single Batch System
 *    - To solve this issue, the Batch System was introduced.
 *    - Instead of loading one program at a time manually:
 *      > Multiple programs were collected.
 *      > They are grouped into a batch.
 *      > The batch was loaded once.
 *      > The CPU executed them one by one automatically.
 *    - Now:
 *      > No need to manually load each program.
 *      > CPU did not stay idle b/w jobs.
 *      > Efficiently improved.
 * 
 * 4. Simple Flow:
 *    a. Before Batch System:
 *       - Load → Run → Stop → Load → Run → Stop 
 *       - Manual work everytime
 *    b. After Batch System:
 *       - Load All Jobs → Run Job 1 → Run Job 2 → Run Job 3 
 *       - Automatic Execution
*/