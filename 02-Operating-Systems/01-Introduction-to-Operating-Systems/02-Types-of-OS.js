/**
 * Operating System (OS):
 * > Imagine a computer without an Operating System.
 * > A computer has hardware like CPU, memory, keyboard, mouse, and
 *   storage. But hardware does not understand human language. It only
 *   understands machine-level instructions.
 * > So here is the problem:
 *   - The user does not understand machine language.
 *   - The hardware does not understand human language.
 *   - Multiple programs may want to use the CPU at the same time.
 *   - Memory and storage need to be managed properly.
 *   - Without control, everything would conflict.
 * > So the main problem is:
 *   "How can users use hardware easily and safely?"
 * 
 * Solution: Operatins System
 * > OS acts as a middle layer b/w the user and the hardware.
 * > It manages resources and makes communication possible.
 *   [ User > OS > Hardware ]
 * > Instead of talking directly to hardware, the user talks to the OS
 * > The OS understands the request and gives instructions to the
 *   hardware.
*/

/**
 * What is Operating System (OS)?
 * > An OS is the main system software that:
 *   - Manages hardware resources
 *   - Controls running programs
 *   - Provides an interface for users
 *   - Makes sure everything works smoothly
 * > It starts when the computer starts and keeps running in the 
 *   background.
 * 
 * Simple Words:
 * > OS is a manager that controls hardware and helps users run programs
 *   in an organized and safe way.
*/

